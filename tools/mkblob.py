#!/usr/bin/env python3
"""mkblob.py [out | --header]: the local servers' 256 KiB download, deterministic: block i (32 B) is SHA-256 of i as
4 bytes big-endian. With out, writes it; with --header, prints certs/blob.h: its length and SHA-256, and the reply
tools/app_server.py's /echo must give for its first ECHO_LEN bytes. Otherwise prints the length and SHA-256."""
import hashlib, struct, sys

ECHO_LEN = 8192
blob = b"".join(hashlib.sha256(struct.pack(">I", i)).digest() for i in range(8192))

def c_array(name, data):
    hexes = ["0x%02x" % b for b in data]
    rows = [", ".join(hexes[i:i + 12]) for i in range(0, len(hexes), 12)]
    return "static const uint8_t %s[32] = {\n    %s\n};" % (name, ",\n    ".join(rows))

if len(sys.argv) > 1 and sys.argv[1] == "--header":
    echo_reply = (hashlib.sha256(blob[:ECHO_LEN]).hexdigest() + "\n").encode()
    print("// Generated by tools/mkblob.py --header")
    print("#define BLOB_LEN %d" % len(blob))
    print(c_array("blob_sha256", hashlib.sha256(blob).digest()))
    print("#define ECHO_LEN %d // POST /echo sends the blob's first ECHO_LEN bytes" % ECHO_LEN)
    print("#define ECHO_REPLY_LEN %d" % len(echo_reply))
    print(c_array("echo_reply_sha256", hashlib.sha256(echo_reply).digest()))
    sys.exit(0)
if len(sys.argv) > 1:
    open(sys.argv[1], "wb").write(blob)
print(len(blob), hashlib.sha256(blob).hexdigest())
