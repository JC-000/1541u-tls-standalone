# mkcerts.sh: the test PKI for the local OpenSSL servers (OpenSSL >= 3.4 for -not_before/-not_after).
# Writes certs/: a private CA (embedded in the app as the CUSTOM CA), the leaves the servers use, and
# pins.h with the SHA-256 of the good leaf's SubjectPublicKeyInfo (trust mode PIN).
# Test keys only; they protect nothing.
set -euo pipefail
cd "$(dirname "$0")/../certs"
rm -f *.pem *.der *.srl pins.h
ec() { openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out "$1" 2>/dev/null; }

ec ca.key.pem
openssl req -x509 -new -key ca.key.pem -subj "/CN=1541u-tls-standalone test CA" \
    -not_before 20240101000000Z -not_after 20361231235959Z \
    -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign,cRLSign" -out ca.pem
openssl x509 -in ca.pem -outform DER -out ca.der

leaf() { # name SAN not_before not_after
    ec "$1.key.pem"
    openssl req -new -key "$1.key.pem" -subj "/CN=$2" -out "$1.csr"
    openssl x509 -req -in "$1.csr" -CA ca.pem -CAkey ca.key.pem -CAcreateserial -not_before "$3" -not_after "$4" \
        -extfile <(printf "subjectAltName=DNS:%s\nbasicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\n" "$2") \
        -out "$1.pem" 2>/dev/null
    rm -f "$1.csr"
}
NOW=$(date -u -v-1d +%Y%m%d%H%M%SZ 2>/dev/null || date -u -d '-1 day' +%Y%m%d%H%M%SZ)
leaf good tls.test "$NOW" 20351231235959Z
leaf wronghost other.test "$NOW" 20351231235959Z
leaf expired tls.test 20240601000000Z 20250101000000Z

# Self-signed, for tls.test: no CA vouches for it
ec selfsigned.key.pem
openssl req -x509 -new -key selfsigned.key.pem -subj "/CN=tls.test" -not_before "$NOW" -not_after 20351231235959Z \
    -addext "subjectAltName=DNS:tls.test" -out selfsigned.pem

PIN=$(openssl x509 -in good.pem -pubkey -noout | openssl pkey -pubin -outform DER | openssl dgst -sha256 -binary | xxd -i)
{
    echo "// Generated by tools/mkcerts.sh: SHA-256 of certs/good.pem's SubjectPublicKeyInfo"
    echo "static const uint8_t pin_good[32] = {"
    echo "$PIN"
    echo "};"
} > pins.h
rm -f *.srl
ls -l
